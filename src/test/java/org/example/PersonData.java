package org.example;

public class PersonData {
    public String name;
    public String surname;
    public String address;
    public String subway;
    public String phone;

    public PersonData(String name, String surname, String address, String subway, String phone) {
        this.name = name;
        this.surname = surname;
        this.address = address;
        this.subway = subway;
        this.phone = phone;
    }

}
